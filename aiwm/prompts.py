"""给模型的两段提示词。

放在这里而不是 `main.py`：`main.py` 顶层 import astrbot，本地跑不了单测，而
提示词里那些**硬性的输出格式与反端水约定**是要被测试钉住的。

两条经验写在提示里，也写在测试里：

1. **称号那一行必须以「你最近是个」开头**，模型很爱自由发挥成「称号：xxx」。
2. **PK 的对比由代码算好再交给模型**（见 `stats.对比要点`）。让模型自己比，它
   最省事的答案就是「各有千秋」这类端水话。所以提示里明确写死「不许推翻
   对比结论」「分差至少 10 分」，并把端水词列成禁令。
"""

from __future__ import annotations

__all__ = ["称号前缀", "端水词", "锐评提示", "PK提示"]

# 称号那一行必须这么开头。提示词里写一遍，测试里再钉一遍。
称号前缀 = "你最近是个"

# 反端水禁令。列出来比说「不要端水」有效——模型对具体词表最敏感。
端水词 = (
    "各有千秋",
    "不相上下",
    "势均力敌",
    "难分伯仲",
    "都很强",
    "继续努力",
    "加油",
    "都有提升空间",
    "提升空间很大",
)

_锐评骨架 = f"""\
{称号前缀}<称号>

<两三句总评：这份数据说明了什么>

打得好：<点到具体武器或地图与数据，说清他真正靠什么赢>
问题：<点出数据里最扎眼的一处短板>
建议：<一条今天就能照做的具体做法>"""


def 锐评提示(数据: str) -> str:
    """锐评的提示词。数据是 `aiwm.stats.汇总文本` 的输出。"""
    return (
        "下面是一个玩家自己的 CS2（完美世界竞技平台）近期战绩统计。请写一段锐评，"
        "严格按下面的格式输出，不要前言、不要标题、不要编号：\n\n"
        f"{_锐评骨架}\n\n"
        "硬要求：\n"
        f"- 第一行必须以「{称号前缀}」开头，后面接不超过 18 字的称号；称号里要带上"
        "他的段位或招牌武器，例如「你最近是个靠 AK 压点的大地球老油条」。\n"
        "- 称号要贴着数据说，别写成「枪法准」这类放在谁身上都成立的废话。\n"
        "- 后面四个小标题原样保留（打得好／问题／建议），每段一句话。\n"
        "- 全文至少出现 3 个具体数字（胜率、KD、ADR、KAST、爆头率之类），"
        "不许通篇形容词。\n"
        "- 「问题」那一段必须指向数据里的具体一项；"
        "不许写「多练枪」「注意配合」这种没落到数据上的话。\n"
        "- 若 KAST 或首杀率明显偏低，就拿这两项说问题，它们直接反映"
        "「该打的团没打」和「没人给你第一枪」；若爆头率低，说中远距离的枪法。\n"
        f"- 禁止出现这些端水词：{'、'.join(端水词)}。\n"
        "- 不要复述数据原文，不要「首先／其次／总而言之」，不要客套。\n"
        "- 全文 180 到 260 字。\n\n"
        "数据：\n"
        f"{数据}"
    )


def PK提示(
    甲名: str,
    乙名: str,
    对比: str,
    占优: str,
    甲数据: str,
    乙数据: str,
) -> str:
    """两人 PK 的提示词。

    `对比` 与 `占优` 都由 `stats.对比要点` 算好——模型不做比较，只做解说。
    """
    return (
        f"下面是 {甲名} 和 {乙名} 的 CS2 近期战绩。逐项对比**已经替你算好了**，"
        "你的任务只是解说和打分：不要重算、不要推翻对比结论、不要两边都给好评。\n\n"
        "严格按下面的格式输出，不要前言、不要标题、不要编号：\n\n"
        f"{甲名} <分数>\n"
        f"{乙名} <分数>\n"
        "胜者：<名字>\n"
        "逐项：<挑差异最大的 3 项，写成「项名：谁占优（谁的数字 对 谁的数字）」>\n"
        "互损：<两三句>\n\n"
        "硬要求：\n"
        "- 分数取 0-100 的整数，根据实际情况给出分数差距，要敢于给大的分数差距。\n"
        "- 占优项更多的一方不一定分数更高，一切从实际出发。"
        f"占优项数仅供参考：{占优}\n"
        "- 「逐项」那行必须写出项名与双方数字。\n"
        "- 「互损」必须点名双方最难看的那一项，带上具体数字或武器名，"
        "对于输的一方点名更狠一点。\n"
        f"- 禁止出现这些端水词：{'、'.join(端水词)}。\n"
        "- 「互损」至少 90 字，不许一句话打发。\n"
        "- 不要复述数据原文，不要「首先／其次／总而言之」。\n\n"
        "已算好的逐项对比：\n"
        f"{对比}\n\n"
        f"【{甲名}】原始数据\n{甲数据}\n\n【{乙名}】原始数据\n{乙数据}"
    )
