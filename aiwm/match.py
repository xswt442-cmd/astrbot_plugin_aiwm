"""「开一局」的对局设定。

这一局是**推演出来的，不是真实战绩**。所有数字都由这里用随机数生成，不让模型
自己编——模型编的数字既不服从概率，看起来也不像真人。

随机的东西要贴近真人：击杀数不能均匀分布，团队获胜的局个人表现一般不会太拉，
评级在一局里的起伏比分数小。
"""

from __future__ import annotations

import random
from typing import Any

__all__ = ["开局设定", "设定文本", "侧写", "选地图", "选武器", "武器类别"]

# 完美平台在 CS2 里的地图。挑的是玩家真会遇到的池子，不含竞技模式专属图。
地图池 = (
    "远古遗迹",
    "炼狱小镇",
    "荒漠迷城",
    "核子危机",
    "死城之谜",
    "列车停放站",
    "古堡激战",
    "炼狱小镇",
)

# 武器按类别给命中率区间，用同一套逻辑派生出这一局的命中与爆头数。
武器类别 = {
    "AK47": (0.28, 0.42),
    "M4A4": (0.26, 0.40),
    "M4A1消音型": (0.30, 0.44),
    "AWP": (0.62, 0.80),
    "大地球": (0.72, 0.90),
    "沙漠之鹰": (0.30, 0.46),
    "P250": (0.24, 0.38),
    "Tec-9": (0.25, 0.40),
    "MP9": (0.24, 0.38),
    "UMP-45": (0.26, 0.40),
    "Nova": (0.20, 0.34),
    "XM1014": (0.18, 0.32),
}

# 手枪在残局与下ECO局才会拿得比较显眼，整局里权重低一些。
武器权重 = {
    "AK47": 10,
    "M4A4": 9,
    "M4A1消音型": 8,
    "AWP": 6,
    "大地球": 4,
    "沙漠之鹰": 3,
    "MP9": 3,
    "Tec-9": 3,
    "UMP-45": 3,
    "P250": 2,
    "Nova": 2,
    "XM1014": 2,
}

# 段位分到大致水平。人一局里的表现不会脱离自己的水平太多。
段位区间 = (
    (1000, 6000, "白银到黄金段"),
    (6000, 12000, "大地球到传奇段"),
    (12000, 20000, "传奇到神话段"),
    (20000, 28000, "神话到超凡段"),
)


def _加权取(随机源: random.Random, 权重表: dict[str, int]) -> str:
    名单 = list(权重表)
    权重 = [权重表[名] for 名 in 名单]
    return 随机源.choices(名单, weights=权重, k=1)[0]


def 选地图(随机源: random.Random) -> str:
    return 随机源.choice(地图池)


def 选武器(随机源: random.Random) -> str:
    return _加权取(随机源, 武器权重)


def 侧写(随机源: random.Random, 段位分: float) -> str:
    """给一个段位分，返回水平描述。用来在提示里告诉模型这个人大概什么水平。"""
    for 下界, 上界, 描述 in 段位区间:
        if 下界 <= 段位分 < 上界:
            return 描述
    return 段位区间[-1][2]


def 开局设定(随机源: random.Random, 统计: dict[str, Any] | None) -> dict[str, Any]:
    """生成一局的完整设定。

    `统计` 是玩家真实的近期统计，用它决定这一局的水平——没有就按中间档来。
    这样推演出来的表现贴着这人平时的水平，而不是凭空一个路人。

    固定两件事：**比分走 13 局**（CS2 竞技的赛制），**评级不会比上局掉太多**
    （一局里大幅掉分要出意外状况，绝大多数时候是平的）。
    """
    if 统计 and 统计.get("总场次"):
        水平 = 统计
    else:
        水平 = {}

    地图 = 选地图(随机源)
    武器 = 选武器(随机源)
    命中率下, 命中率上 = 武器类别[武器]

    # 个人表现随水平浮动。没有真实数据时取中位，不假装知道他什么水平。
    基础击杀 = 水平.get("KD") or 1.0
    基础爆头 = 水平.get("爆头率")
    基础爆头 = 基础爆头 / 100 if 基础爆头 else 0.5

    是否胜利 = 随机源.random() < 0.5
    得分 = 13 if 是否胜利 else 随机源.randint(9, 12)
    失分 = 13 if not 是否胜利 else 随机源.randint(9, 12)

    击杀 = max(
        0,
        round(随机源.triangular(8, 32, 8 + 基础击杀 * 9) + (2 if 是否胜利 else -2)),
    )
    死亡 = max(1, round(击杀 / max(0.35, 基础击杀)))
    助攻 = max(0, round(击杀 * 随机源.uniform(0.2, 0.6)))

    爆头数 = min(击杀, round(击杀 * 随机源.triangular(0.2, 0.75, 基础爆头)))
    命中率 = 随机源.uniform(命中率下, 命中率上)
    伤害 = round(击杀 * 随机源.uniform(88, 108) + 死亡 * 随机源.uniform(20, 45))

    上局评级 = 水平.get("近十场评分") or []
    参照 = 上局评级[0] if 上局评级 else 1.0
    评级 = round(max(0, min(2, 随机源.gauss(参照, 0.3))), 2)

    段位分 = 水平.get("段位分") or 0

    return {
        "地图": 地图,
        "武器": 武器,
        "是否胜利": 是否胜利,
        "比分": f"{得分}:{失分}",
        "击杀": 击杀,
        "死亡": 死亡,
        "助攻": 助攻,
        "爆头数": 爆头数,
        "命中率": round(命中率 * 100, 1),
        "伤害": 伤害,
        "评级": 评级,
        "首杀": 随机源.random() < 0.45,
        "残局": 随机源.choice(("打出一次 1v2 残局", "被残局翻盘", "残局站住了", "残局白给")),
        "走位": 随机源.choice(
            ("中路架点稳", "开局抢点激进", "被打得退守", "绕后拿了个侧翼", "跟着队友进点")
        ),
        "水平": 侧写(随机源, 段位分) if 段位分 else "无历史数据，取中等水平",
    }


def 设定文本(设定: dict[str, Any]) -> str:
    """把设定折成给模型读的文字。"""
    行 = [
        f"地图：{设定['地图']}",
        f"武器：{设定['武器']}",
        f"比分：{设定['比分']}（{'胜' if 设定['是否胜利'] else '负'}）",
        f"击杀/死亡/助攻：{设定['击杀']}/{设定['死亡']}/{设定['助攻']}",
        f"爆头：{设定['爆头数']}，命中率 {设定['命中率']}%",
        f"伤害：{设定['伤害']}",
        f"本局评级：{设定['评级']}",
        f"拿到首杀：{'是' if 设定['首杀'] else '否'}",
        f"残局：{设定['残局']}",
        f"走位：{设定['走位']}",
        f"玩家水平：{设定['水平']}",
    ]
    return "\n".join(行)
