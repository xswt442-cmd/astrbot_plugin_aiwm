"""指令落空时的兜底。

`/爱完美 <任意内容>` 而内容没匹配上任何子命令时，`CommandGroupFilter.filter`
返回 False，指令被跳过，**消息原样进模型**。模型收到的是一句普通提问，于是
自己编答案：实测用户发 `/爱完美 <steam 个人资料页链接>`，模型回「打不开Steam，
你发链接干嘛，考验我视力？」，还自称「我又没权限爬Steam」——它并不在查 Steam，
它在编。

用户没打错指令，是这条指令没接住。所以指令组挂一个兜底过滤器：匹配了组名但
没匹配任何子命令时，自己回一句提示，把消息拦在这里。

只拦「以组名开头」的，`/爱完美` 单独一条由 AstrBot 自己处理（它会列出全部
子命令），不重复。
"""

from __future__ import annotations

__all__ = ["子命令名", "取落空参数", "是否落空", "落空提示"]

# 全部子命令与别名。少一个别名，用户打那个别名时就落空了。
# 改 main.py 里的指令或别名，这里要跟着改——`test_main_wiring.py` 会核对。
子命令名 = frozenset(
    {
        # 子命令
        "战绩",
        "锐评",
        "开一局",
        "PK",
        "昵称",
        "解绑",
        "状态",
        "帮助",
        "绑定",
        # 别名
        "绑定steamid",
        "pk",
        "对战",
        "开局",
        "来一局",
        "help",
        "菜单",
        "status",
    }
)


def 取落空参数(消息: str, 组名: str) -> str:
    """取出组名后面的内容。

    组名可能带 `/` 前缀也可能不带——QQ 官方适配器有时会把 `message_str` 里的
    `/` 去掉，所以两种都得认。
    """
    文本 = (消息 or "").strip()
    for 前缀 in (f"/{组名}", 组名):
        if 文本.startswith(前缀):
            剩余 = 文本[len(前缀) :].strip()
            # 组名重复出现时（`/爱完美 /爱完美 战绩`）只取第一处之后的
            return 剩余
    return 文本


def 是否落空(消息: str, 组名: str) -> bool:
    """这条消息是不是「匹配了组名但没匹配任何子命令」。

    判据必须与 `CommandGroupFilter.startswith` 一致——**字面前缀匹配**，否则
    会吃掉正常指令。

    消息完全等于组名（`/爱完美`）不算落空：`filter` 那时会抛错列出全部子
    指令，不归这里管，不然两组提示会叠着发。
    """
    参数 = 取落空参数(消息, 组名)
    if not 参数:
        return False
    return not any(参数.startswith(名) for 名 in 子命令名)


def 落空提示(参数: str) -> str:
    """没有子命令匹配时回什么。

    带参数就当用户是想绑定——实测落空绝大多数是这个：打了 id 或链接，以为
    `/爱完美 <id>` 就等于绑定。不带参数就列几个子命令。
    """
    干净 = (参数 or "").strip()
    if not 干净:
        return (
            "要看战绩发 /爱完美 战绩，要锐评发 /爱完美 锐评，"
            "要绑定发 /爱完美 绑定 <steamid64>。全部指令发 /爱完美 帮助。"
        )

    # 参数短就原样带回去让用户复制，太长就只说清楚该怎么做——一整段日志回显
    # 出来没意义
    回显 = 干净 if len(干净) <= 40 else f"{干净[:40]}…"
    return f"「{回显}」不是子命令。要绑定这个号用：/爱完美 绑定 {回显}"
